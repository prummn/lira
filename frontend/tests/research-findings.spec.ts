import { test, expect } from '@playwright/test'

test('collection offers research types without requiring a model connection to save direction', async ({page,request}) => {
  const c=await (await request.post('/api/collections',{data:{name:'Findings setup'}})).json()
  await page.goto('/')
  await page.locator('.collection-nav').getByRole('button',{name:c.name,exact:true}).click()
  await page.getByRole('button',{name:'研究线索',exact:true}).click()
  await expect(page.getByRole('heading',{name:'下一次阅读，从一个好问题开始。'})).toBeVisible()
  await page.getByRole('button',{name:'选择研究任务',exact:true}).click()
  const dialog=page.getByRole('dialog',{name:'专题研究设置'})
  await expect(dialog.getByRole('checkbox',{name:/允许这个专题在闲时研究/})).not.toBeChecked()
  await expect(dialog.getByRole('checkbox',{name:'后台总开关',exact:true})).not.toBeChecked()
  for(const label of ['发现论文联系','检查知识缺口','准备复习题','提出研究问题'])await dialog.getByLabel(label,{exact:true}).check()
  await dialog.getByRole('textbox',{name:'研究方向',exact:true}).fill('关注记忆如何进入决策。')
  await dialog.getByRole('button',{name:'保存研究方向',exact:true}).click()
  await expect(dialog).not.toBeVisible()
  const state=await (await request.get(`/api/research/collections/${c.id}/findings`)).json()
  expect(state.scope.work_types).toEqual(['essay','connections','gaps','review','questions'])
  expect(state.scope.focus).toContain('记忆')
})

test('findings support filters, decisions, hidden answers, history and source navigation', async ({page,request}) => {
  const c=await (await request.post('/api/collections',{data:{name:'Findings reading'}})).json()
  const source={id:'S1',paper_id:'paper-001',title:'Original memory study',page:2,section:'Method',chunk_id:'chunk-1',text:'Stored memories are retrieved before the next action.',quote:'Stored memories are retrieved before the next action.',claim:'A retrieval step.'}
  const items=['connection','gap','review','question'].map((kind,i)=>({id:`f${i}`,collection_id:c.id,kind,title:['同一次检索，改变了什么？','当前材料还缺少删除记忆的行为证据','历史何时重新进入推理？','检索失败会改变后续计划吗？'][i],body:`一次经历需要在检索后重新进入当前上下文。这里可以逐步检查机制。[1](#source-S1)`,next_step:'依据 S1 对照。公式 $S1+1$ 与 `S1` 保持原样。',sources:[source],status:'unread',review_count:0,due_at:kind==='review'?'2020-01-01T00:00:00Z':null,model:'fixture',created_at:'2026-10-24T09:00:00Z',updated_at:'2026-10-24T09:00:00Z'}))
  await page.route(`**/api/research/collections/${c.id}/findings`,route=>route.fulfill({json:{items,scope:{enabled:true,focus:'记忆如何改变行动',work_types:['connections','gaps','review','questions']},task:null,due_count:1}}))
  await page.route('**/api/research/findings/f*',route=>{
    const id=route.request().url().split('/').pop()!
    const item=items.find(i=>i.id===id)!
    const action=route.request().postDataJSON().action
    Object.assign(item,{status:({keep:'kept',dismiss:'dismissed',restore:'unread',done:'done',remembered:'kept'} as Record<string,string>)[action]??'kept'})
    if(action==='remembered')Object.assign(item,{review_count:1,due_at:'2030-01-01T00:00:00Z'})
    return route.fulfill({json:item})
  })
  await page.route('**/api/research/findings/*/history',route=>route.fulfill({json:{revisions:[{...items[0],id:'rev1'}]}}))
  await page.goto('/')
  await page.locator('.collection-nav').getByRole('button',{name:c.name,exact:true}).click()
  await page.getByRole('button',{name:'研究线索',exact:true}).click()
  await expect(page.getByRole('heading',{name:items[0].title,exact:true})).toBeVisible()
  await page.getByRole('button',{name:'保留线索',exact:true}).click()
  await page.getByRole('button',{name:'忽略线索',exact:true}).click()
  await page.getByLabel('线索状态').selectOption('dismissed')
  await page.getByRole('button',{name:items[0].title,exact:true}).click()
  await page.getByRole('button',{name:'恢复线索',exact:true}).click()
  await page.getByLabel('线索状态').selectOption('active')
  await page.getByLabel('线索类型').selectOption('review')
  await expect(page.getByRole('heading',{name:items[2].title,exact:true})).toBeVisible()
  await expect(page.locator('.finding-answer')).toHaveCount(0)
  await page.getByRole('button',{name:'展开参考答案',exact:true}).click()
  await expect(page.locator('.finding-answer')).toContainText('重新进入当前上下文')
  await expect(page.locator('.finding-next').getByRole('button',{name:'查看原文 1',exact:true})).toBeVisible()
  await expect(page.locator('.finding-next code')).toHaveText('S1')
  await page.getByRole('button',{name:'记住了',exact:true}).click()
  await expect(page.locator('.finding-review')).toContainText('下次复习')
  await page.getByRole('button',{name:'查看原文 1',exact:true}).first().click()
  await expect(page.getByRole('dialog',{name:'原文出处'})).toContainText(source.quote)
  await page.getByRole('button',{name:'在论文中查看',exact:true}).click()
  await expect(page.getByRole('button',{name:'返回研究线索',exact:true})).toBeVisible()
  await page.getByRole('button',{name:'返回研究线索',exact:true}).click()
  await expect(page.getByRole('heading',{name:items[2].title,exact:true})).toBeVisible()
  await expect(page.locator('.finding-answer')).toContainText('重新进入当前上下文')
  await page.getByRole('button',{name:'修订记录',exact:true}).click()
  await expect(page.locator('.finding-history')).toContainText('fixture')
  await page.setViewportSize({width:430,height:850})
  await page.getByRole('button',{name:'主题',exact:true}).click()
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
  await page.screenshot({path:'test-artifacts/research-findings-narrow-dark.png',fullPage:true})
  await page.getByRole('button',{name:'返回线索列表',exact:true}).click()
  await expect(page.locator('.findings-list')).toBeVisible()
})

test('a late history response cannot move to another finding', async ({page,request}) => {
  const c=await (await request.post('/api/collections',{data:{name:'History request ordering'}})).json()
  const items=['First question','Second question'].map((title,i)=>({id:`h${i}`,kind:'question',title,body:'Explain the mechanism.',next_step:'Trace one event.',sources:[],status:'unread',model:'fixture',review_count:0,due_at:null,created_at:'2026-10-24T09:00:00Z',updated_at:'2026-10-24T09:00:00Z'}))
  await page.route(`**/api/research/collections/${c.id}/findings`,route=>route.fulfill({json:{items,scope:{enabled:false,focus:'',work_types:['questions']},task:null,due_count:0}}))
  let release!:()=>void
  let requested!:()=>void
  const received=new Promise<void>(resolve=>{requested=resolve})
  const held=new Promise<void>(resolve=>{release=resolve})
  await page.route('**/api/research/findings/h0/history',async route=>{requested();await held;await route.fulfill({json:{revisions:[{...items[0],id:'old-rev'}]}})})
  await page.goto('/')
  await page.locator('.collection-nav').getByRole('button',{name:c.name,exact:true}).click()
  await page.getByRole('button',{name:'研究线索',exact:true}).click()
  await page.getByRole('button',{name:'修订记录',exact:true}).click()
  await received
  await page.getByRole('button',{name:items[1].title,exact:true}).click()
  const response=page.waitForResponse(r=>r.url().endsWith('/findings/h0/history'))
  release();await response
  await expect(page.getByRole('button',{name:'修订记录',exact:true})).toBeEnabled()
  await expect(page.locator('.finding-history')).toHaveCount(0)
})
